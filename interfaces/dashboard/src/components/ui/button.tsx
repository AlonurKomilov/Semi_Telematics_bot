// ``forwardRef`` so callers (e.g. DataGrid's Manage-columns popover
// anchor) can attach a ref to the underlying button.  Without this,
// ``<Button ref={...}>`` would silently drop the ref on React 18
// (the primitive itself is forward-ref'd, but the wrapper wasn't).
const Button = React.forwardRef<
  HTMLButtonElement,
  ButtonPrimitive.Props & VariantProps<typeof buttonVariants>
>(function Button({ className, variant = "default", size = "default", ...props }, ref) {
  return (
    <ButtonPrimitive
      ref={ref}
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  )
})

export { Button, buttonVariants }
