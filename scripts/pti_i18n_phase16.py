def _set_nested(d: dict, dotted_key: str, value) -> None:
    parts = dotted_key.split(".")
    cur = d
    for p in parts[:-1]:
        if p not in cur or not isinstance(cur[p], dict):
            cur[p] = OrderedDict()
        cur = cur[p]
    cur[parts[-1]] = value


def _patch_locale(path: Path, translations: dict) -> int:
    data = json.loads(path.read_text(), object_pairs_hook=OrderedDict)
    added = 0
    for key, value in translations.items():
        parts = key.split(".")
        cur = data
        exists = True
        for p in parts:
            if not isinstance(cur, dict) or p not in cur:
                exists = False
                break
            cur = cur[p]
        if exists:
            continue
        _set_nested(data, key, value)
        added += 1
    if added:
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    return added


def main(repo: Path) -> None:
    dash_dir = repo / "interfaces/dashboard/src/locales"
    mini_dir = repo / "interfaces/miniapp/src/locales"
    for loc in LOCALES:
        d = dash_dir / f"{loc}.json"
        if d.exists() and loc in DASH:
            n = _patch_locale(d, DASH[loc])
            print(f"dashboard {loc}: +{n} keys")
        m = mini_dir / f"{loc}.json"
        if m.exists() and loc in MINI:
            n = _patch_locale(m, MINI[loc])
            print(f"miniapp   {loc}: +{n} keys")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else "."))
