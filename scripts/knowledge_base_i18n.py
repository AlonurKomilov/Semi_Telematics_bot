def merge(base: dict, override: dict) -> dict:
    out = OrderedDict(base.items())
    for k, v in override.items():
        out[k] = v
    return out


def apply_to(locale: str) -> None:
    path = LOCALE_DIR / f"{locale}.json"
    data = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=OrderedDict)
    overrides = OVERRIDES.get(locale, {})
    block = merge(EN, overrides)
    data["knowledge"] = block
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"  {locale}: ok")


def main() -> int:
    print(f"Propagating knowledge i18n to {len(LOCALES)} locales:")
    for loc in LOCALES:
        apply_to(loc)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
